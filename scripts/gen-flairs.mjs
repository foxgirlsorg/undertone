// Generates src/styles/flairs.css: ListenBrainz's flairs.scss (GPL-2.0) compiled by hand to plain CSS,
// with the SCSS @for loops expanded. Run from the project root.
import fs from "node:fs";
const ORANGE = "#eb743b";
const BLUE = "#7f7bd6"; // ListenBrainz blue, lightened so it reads on a black background
const RED = "#ff3b3b";
const CYAN = "#00e5ff";
const BG = "#000";

const delays = (selector, step) =>
  Array.from({ length: 20 }, (_, i) => `${selector}:nth-child(${i + 1}) { animation-delay: ${((i + 1) * step).toFixed(2)}s; }`).join("\n");

const css = `/*
  Name flairs, ported from ListenBrainz (frontend/css/sass/flairs.scss, GPL-2.0) so they look the same here.
  Generated by scripts/gen-flairs.mjs; edit that, not this file. Markup: see src/components/ui/flair-name.tsx.
*/
.flair { position: relative; display: inline-block; --text-color: currentColor; }
.flair > span { display: inline-block; }
@media (prefers-reduced-motion: reduce) {
  .flair, .flair::after, .flair::before, .flair > span { animation: none !important; transition: none !important; }
}

/* Shake: a glitchy copy of the name jitters every few seconds (needs data-text). */
.flair.shake::before, .flair.shake::after {
  content: attr(data-text); position: absolute; top: 0; left: 0; width: 100%; height: 100%;
  animation: flair-shake 3s infinite; color: inherit;
}
@keyframes flair-shake {
  0% { opacity: 1; left: 0; top: 0; }
  3% { left: -2px; top: -2px; }
  5% { left: 2px; top: 0; }
  7% { left: -1px; top: 2px; }
  9% { left: 1px; top: -1px; }
  10% { left: 0; top: -2px; opacity: 1; }
  11%, 100% { opacity: 0; left: 0; top: 0; }
}

/* Colour and light sweeps across the letters. */
.flair.lb-colors-sweep, .flair.light-sweep { color: var(--text-color); }
.flair.lb-colors-sweep > span, .flair.light-sweep > span {
  transform-origin: 50% 50% -0.3em; position: relative;
  animation-timing-function: ease-in; animation-duration: 2s; animation-iteration-count: infinite;
}
${delays(".flair.lb-colors-sweep > span", 0.1)}
${delays(".flair.light-sweep > span", 0.1)}
.flair.lb-colors-sweep > span { animation-name: flair-lb-colors-sweep; }
@keyframes flair-lb-colors-sweep { 0%, 9%, 100% { color: inherit; } 3% { color: ${ORANGE}; } 6% { color: ${BLUE}; } }
.flair.light-sweep > span { animation-name: flair-light-sweep; }
@keyframes flair-light-sweep { 0%, 9%, 100% { color: inherit; } 3% { color: #5a5a5a; } 6% { color: inherit; } }

/* Wave: each letter hops in turn. */
.flair.wave > span { position: relative; animation: flair-wave 3s infinite; animation-timing-function: ease-in; }
${delays(".flair.wave > span", 0.05)}
@keyframes flair-wave { 0%, 6%, 12%, 100% { transform: translateY(0); } 9% { transform: translateY(-3px); } }

/* Flips, one letter after another. */
.flair.flip-horizontal > span, .flair.flip-vertical > span, .flair.flip-3d > span {
  position: relative; animation-timing-function: ease-in; animation-duration: 4s; animation-iteration-count: infinite;
  transform-origin: center 40%;
}
${delays(".flair.flip-horizontal > span", 0.1)}
${delays(".flair.flip-vertical > span", 0.1)}
${delays(".flair.flip-3d > span", 0.1)}
.flair.flip-horizontal > span { animation-name: flair-flip-horizontal; }
.flair.flip-vertical > span { animation-name: flair-flip-vertical; }
.flair.flip-3d > span { animation-name: flair-flip-3d; transform-origin: 50% 50% -0.3em; }
@keyframes flair-flip-horizontal { 0%, 12%, 100% { transform: rotateY(0); } 6% { transform: rotateY(360deg); } }
@keyframes flair-flip-vertical { 0%, 12%, 100% { transform: rotateX(0); } 6% { transform: rotateX(360deg); } }
@keyframes flair-flip-3d { 0%, 8%, 100% { transform: rotateX(0); } 4% { transform: rotateX(-90deg); } 4.01% { transform: rotateX(90deg); } }

/* Extruded: 3D letters. */
.flair.extruded {
  vertical-align: text-bottom; color: ${BG};
  text-shadow: 0 0 var(--text-color), -0.5px 0.5px var(--text-color), -1px 1px var(--text-color), -1.5px 1.5px var(--text-color),
    -2px 2px var(--text-color), -2.5px 2.5px var(--text-color), -3px 3px var(--text-color);
  -webkit-text-stroke: 0.5px rgb(255 255 255 / 0.2);
}

/* Underline that swishes under the name in ListenBrainz colours. */
.flair.underline::after {
  content: ""; position: absolute; width: 100%; transform: scaleX(0); height: 1px; bottom: 0; left: 0;
  background: linear-gradient(to right, ${BLUE}, ${ORANGE}); transform-origin: bottom right; animation: flair-underline 4s infinite;
}
@keyframes flair-underline {
  0% { transform: scaleX(0); transform-origin: bottom left; }
  10% { transform: scaleX(1); transform-origin: bottom left; }
  10.01% { transform: scaleX(1); transform-origin: bottom right; }
  20%, 100% { transform: scaleX(0); transform-origin: bottom right; }
}

/* Tornado: letters spin on the X axis in turn. */
.flair.tornado > span { transform-origin: 50% 50% -6px; position: relative; animation: flair-tornado 4s infinite; animation-timing-function: ease-in; }
${delays(".flair.tornado > span", 0.1)}
@keyframes flair-tornado { 0%, 12%, 100% { transform: rotateX(0); } 6% { transform: rotateX(360deg); } }

/* Highlighter: yellow marker on hover (or always, with .flair-active, for previews). */
.flair.highlighter { z-index: 1; }
.flair.highlighter::before {
  content: " "; display: block; position: absolute; inset: 0; background: #fbf719; z-index: -1;
  transition: transform 0.3s ease; transform: scaleX(0) skewX(-10deg); transform-origin: bottom right;
}
.flair.highlighter:hover::before, .flair.highlighter.flair-active::before { transform: scaleX(1) skewX(-10deg); transform-origin: bottom left; }
.flair.highlighter:hover, .flair.highlighter.flair-active { color: #000; }

/* Anaglyph: red/cyan 3D on hover (or always, with .flair-active). */
.flair.anaglyph { transition: text-shadow 0.3s; }
.flair.anaglyph:hover, .flair.anaglyph.flair-active { text-shadow: 0.06em -1px ${RED}, -0.06em 1px ${CYAN}; }

/* Sliced: the name cut in two with a drop shadow (needs data-text). */
.flair.sliced { color: transparent; }
.flair.sliced::before, .flair.sliced::after { content: attr(data-text); position: absolute; top: 0; right: 0; }
.flair.sliced::before { clip-path: polygon(0% 0%, 100% 0%, 100% 40%, 0% 60%); color: #fff; }
.flair.sliced::after {
  clip-path: polygon(0% 65%, 100% 46%, 100% 100%, 0% 100%); color: transparent;
  background: linear-gradient(178deg, #000 50%, #fff 65%); -webkit-background-clip: text; background-clip: text;
  transform: translateX(-0.1em);
}
`;
fs.mkdirSync("src/styles", { recursive: true });
fs.writeFileSync("src/styles/flairs.css", css);
console.log("wrote src/styles/flairs.css");
